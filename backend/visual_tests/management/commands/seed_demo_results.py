import math
import random
from datetime import timedelta

from django.core.management.base import BaseCommand
from django.utils import timezone

from patients.models import Patient
from visual_tests.models import TestProtocol, TestRun, TestSession


PATIENT_ID = "3b174e30-2c9a-4c45-80ef-405a4dcbd9e2"


class Command(BaseCommand):
    help = "Create a fake completed test session + run with realistic trial data."

    def add_arguments(self, parser):
        parser.add_argument(
            "--patient-id",
            default=PATIENT_ID,
            help="Patient UUID to attach the demo session to.",
        )
        parser.add_argument(
            "--eye",
            default="OD",
            choices=["OD", "OS"],
        )

    def handle(self, *args, **opts):
        patient = Patient.objects.get(pk=opts["patient_id"])
        protocol = TestProtocol.objects.filter(is_active=True).first()
        if not protocol:
            self.stderr.write(
                "No active protocol found. Run `python manage.py seed_protocol` first."
            )
            return

        points = list(protocol.points.all().order_by("point_index"))
        if not points:
            self.stderr.write("Protocol has no points.")
            return

        rng = random.Random(42)
        now = timezone.now()
        start = now - timedelta(minutes=6)

        session = TestSession.objects.create(
            patient=patient,
            protocol=protocol,
            performed_by=None,
            eye=opts["eye"],
            notes="Demo session generated by seed_demo_results.",
        )

        trials = []
        for p in points:
            if p.point_type == "static":
                # ~85% seen, faster reactions for closer points
                radius = math.sqrt(float(p.x_deg or 0) ** 2 + float(p.y_deg or 0) ** 2)
                seen_prob = max(0.55, 0.95 - radius * 0.012)
                seen = rng.random() < seen_prob
                trials.append({
                    "protocol_point_id": str(p.id),
                    "point_index": p.point_index,
                    "point_type": "static",
                    "x_deg": str(p.x_deg) if p.x_deg is not None else None,
                    "y_deg": str(p.y_deg) if p.y_deg is not None else None,
                    "angle_deg": None,
                    "start_radius_deg": None,
                    "is_blindspot_check": p.is_blindspot_check,
                    "result": "seen" if seen else "not_seen",
                    "response_time_ms": (
                        rng.randint(280, 520) + int(radius * 4) if seen else None
                    ),
                    "boundary_x_deg": None,
                    "boundary_y_deg": None,
                    "presented_at": (start + timedelta(seconds=p.point_index * 6)).isoformat(),
                })
            else:
                # Kinetic — boundary lands somewhere between 18 and 32 deg
                angle = float(p.angle_deg or 0)
                boundary_r = rng.uniform(18, 32)
                rad = math.radians(angle)
                bx = math.cos(rad) * boundary_r
                by = math.sin(rad) * boundary_r
                seen = rng.random() < 0.92
                trials.append({
                    "protocol_point_id": str(p.id),
                    "point_index": p.point_index,
                    "point_type": "kinetic",
                    "x_deg": None,
                    "y_deg": None,
                    "angle_deg": str(p.angle_deg) if p.angle_deg is not None else None,
                    "start_radius_deg": (
                        str(p.start_radius_deg) if p.start_radius_deg is not None else None
                    ),
                    "is_blindspot_check": p.is_blindspot_check,
                    "result": "seen" if seen else "not_seen",
                    "response_time_ms": rng.randint(320, 600) if seen else None,
                    "boundary_x_deg": round(bx, 2) if seen else None,
                    "boundary_y_deg": round(by, 2) if seen else None,
                    "presented_at": (start + timedelta(seconds=p.point_index * 6)).isoformat(),
                })

        run = TestRun.objects.create(
            session=session,
            eye=opts["eye"],
            status="completed",
            current_point_index=len(points) - 1,
            fixation_loss_count=rng.randint(0, 3),
            is_fixating=True,
            start_time=start,
            end_time=now,
            trials=trials,
        )

        url = f"http://localhost:5173/test/results?session_id={session.id}"
        self.stdout.write(self.style.SUCCESS(
            f"Created demo session {session.id} with run {run.id} ({len(trials)} trials)."
        ))
        self.stdout.write(self.style.SUCCESS(f"Open: {url}"))
